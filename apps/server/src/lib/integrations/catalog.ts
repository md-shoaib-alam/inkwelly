export const CONFIGURABLE_PROVIDERS = PROVIDERS.filter((p) => !p.builtIn);
export const OFFERED_PROVIDERS = CONFIGURABLE_PROVIDERS.filter((p) => p.offered !== false);
export const BUILT_IN_PROVIDERS = PROVIDERS.filter((p) => !!p.builtIn);

const BY_ID = new Map(PROVIDERS.map((p) => [p.id, p]));

export function getProvider(id: string): IntegrationProvider | undefined {
  return BY_ID.get(id);
}

export function planAllows(plan: PlanTier | null | undefined, minPlan: PlanTier | "any"): boolean {
  if (minPlan === "any") return true;
  if (!plan || !(plan in PLAN_ORDER)) return false;
  return PLAN_ORDER[plan] >= PLAN_ORDER[minPlan];
}

/**
 * "Not set up" and "needs upgrade" are derived, never stored: a row exists only once a
 * school starts connecting a provider.
 */
export function resolveStatus(
  plan: PlanTier | null | undefined,
  provider: IntegrationProvider,
  storedStatus?: string | null,
): ConnectionStatus {
  if (storedStatus === "connected" || storedStatus === "pending" || storedStatus === "error") {
    return storedStatus;
  }
  if (provider.builtIn) return "connected";
  if (provider.offered === false) return "not-offered";
  if (!planAllows(plan, provider.minPlan)) return "locked";
  return "available";
}

/** Field keys the API must encrypt before storage, and the ones it must never return. */
export function secretFieldKeys(provider: IntegrationProvider): string[] {
  return provider.fields.filter((f) => f.sensitive).map((f) => f.key);
}
