// Single source of truth for every third-party provider the platform knows about.
// The school-web UI renders from here; nothing about a provider is hardcoded in the frontend.
// Docs URLs were checked against vendor-owned pages on 2026-09-25. Where a vendor publishes
// no public API reference, `docs` is empty and `setupNote` says who to contact instead.

export type PlanTier = "basic" | "standard" | "premium";

export type ProviderCategory =
  | "accounting"
  | "payments"
  | "communication"
  | "attendance-hardware"
  | "transport"
  | "learning"
  | "finance"
  | "documents"
  | "compliance"
  | "storage";

export type ConnectionStatus =
  | "connected"
  | "pending"
  | "error"
  | "available"
  | "locked"
  | "not-offered";

export type CostModel = "one-time" | "metered" | "licence" | "included" | "commercial";

export interface IntegrationField {
  key: string;
  label: string;
  type: "text" | "secret" | "url" | "select";
  options?: string[];
  placeholder?: string;
  hint?: string;
  /** AES-encrypted into TenantIntegration.secrets; never returned by the API after save. */
  sensitive?: boolean;
  required?: boolean;
}

export interface DocLink {
  label: string;
  url: string;
}

export interface IntegrationProvider {
  id: string;
  name: string;
  vendor: string;
  category: ProviderCategory;
  summary: string;
  whoPays: string;
  costModel: CostModel;
  costNote: string;
  minPlan: PlanTier | "any";
  /** Who is allowed to type the credentials. A platform admin must not become a school's password vault. */
  setupOwner: "school_admin" | "super_admin" | "platform";
  builtIn?: boolean;
  offered?: boolean;
  notOfferedReason?: string;
  docs: DocLink[];
  setupNote?: string;
  fields: IntegrationField[];
}

